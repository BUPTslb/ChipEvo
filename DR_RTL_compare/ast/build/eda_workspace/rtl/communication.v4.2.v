`timescale 1ns / 1ps
module sync_serial_communication_tx_rx(
    input clk,                     // Clock signal
    input reset_n,                 // Active low reset signal
    input [2:0] sel,               // Selection signal for TX block
    input [63:0] data_in,          // 64-bit data input for TX block
    output [63:0] data_out,        // 64-bit data output from RX block
    output done                    // Done signal indicating completion
);

// Internal signals
wire tx_out;                       // Serial data output from TX block
wire tx_done;                      // Done signal from TX block
wire serial_clk_in;                // Serial clock generated by TX block

// Instantiate the TX block
tx_block uut_tx_block (
    .clk(clk),                     // Clock input to TX block
    .reset_n(reset_n),             // Reset input to TX block
    .data_in(data_in),             // 64-bit data input to TX block
    .sel(sel),                     // Selection signal to TX block
    .serial_out(tx_out),           // Serial data output from TX block
    .done(tx_done),                // Done signal from TX block
    .serial_clk(serial_clk_in)     // Serial clock output from TX block
);

// Instantiate the RX block
rx_block uut_rx_block (
    .clk(clk),                     // Clock input to RX block
    .serial_clk(serial_clk_in),    // Serial clock input to RX block
    .reset_n(reset_n),             // Reset input to RX block
    .sel(sel),                     // Selection signal to RX block
    .data_in(tx_out),              // Serial data input to RX block
    .data_out(data_out),           // 64-bit data output from RX block
    .done(done)                    // Done signal from RX block
);

endmodule

///// tx_block
module tx_block(
    input clk,               // Clock input
    input reset_n,           // Active-low reset input
    input [63:0] data_in,    // 64-bit parallel data input
    input [2:0] sel,         // Selection input to choose data width
    output reg serial_out,   // Serial data output
    output reg done,         // Done signal indicating completion of transmission
    output serial_clk        // Clock for serial data transmission
);

// Internal registers
reg [63:0] data_reg;         // Register to hold the data being transmitted
reg [6:0] bit_count;         // Counter to track number of bits to transmit
reg [6:0] reg_count;         // Register for counting bits for serial clock control
reg [6:0] temp_reg_count;    // Temporary register to track reg_count

// One-hot pre-decode for sel signal (L5 optimization)
wire sel_is_000 = (sel == 3'b000);
wire sel_is_001 = (sel == 3'b001);
wire sel_is_010 = (sel == 3'b010);
wire sel_is_011 = (sel == 3'b011);
wire sel_is_100 = (sel == 3'b100);

// Condition pre-computation for done signal (L5 optimization)
wire bit_count_is_zero = (bit_count == 7'h0);
wire bit_count_positive = (bit_count > 7'h0);

// L5 optimization: Pre-compute data_reg load value outside always block (late mux-select)
// This separates the sel→data path from the done_condition→data_reg path.
// The sel mux tree and done_condition evaluate in parallel; only a 2:1 mux
// at the data_reg register input depends on both.
wire [63:0] data_reg_load_slice = (sel_is_001) ? {56'h0, data_in[7:0]} :
                                  (sel_is_010) ? {48'h0, data_in[15:0]} :
                                  (sel_is_011) ? {32'h0, data_in[31:0]} :
                                  (sel_is_100) ? data_in[63:0] :
                                  64'h0;

// Sequential block for state control and data selection
always @(posedge clk or negedge reset_n) begin
    if (!reset_n) begin
        // Reset all values on active-low reset
        data_reg     <= 64'h0;                              // Clear the data register
        bit_count    <= 7'h0;                               // Reset bit count to zero
        reg_count    <= 7'h0;                               // Reset reg_count to zero
    end else begin
        if (done == 1'b1) begin
            // L5 optimization: Use pre-computed slice for data_reg load.
            // Reduced from 5-level ternary inside conditional to simple 2:1 mux.
            // sel mux tree and done/condition evaluate in parallel.
            data_reg  <= data_reg_load_slice;
            // bit_count still set by sel-dependent value
            if (sel_is_000) begin
                bit_count <= 7'd0;
            end else if (sel_is_001) begin
                bit_count <= 7'd7;
            end else if (sel_is_010) begin
                bit_count <= 7'd15;
            end else if (sel_is_011) begin
                bit_count <= 7'd31;
            end else if (sel_is_100) begin
                bit_count <= 7'd63;
            end else begin
                bit_count <= 7'h0;
            end
        end else if (bit_count_positive) begin
            data_reg   <= data_reg >> 1;                    // Shift the data to the right
            bit_count  <= bit_count - 1'b1;                 // Decrement the bit count
        end
        reg_count <= bit_count;                             // Update reg_count for serial clock control
    end
end

// Generate serial clock based on reg_count
assign serial_clk = clk && (temp_reg_count !== 7'd0);

// Register to keep track of reg_count and use for clock gating
always@(posedge clk or negedge reset_n) begin 
    if(!reset_n) begin
        temp_reg_count <= 7'h0;                             // Reset temporary reg_count
    end
    else begin
        temp_reg_count <= reg_count;                        // Update temp_reg_count with current reg_count
    end
end

// L5 optimization: Pre-compute serial_out enable condition as wire (condition precompute)
// Separates comparison from register input mux
wire reg_count_positive = (reg_count > 7'h0);
wire serial_out_enable = reg_count_positive || bit_count_positive;

// Sequential logic to drive the serial_out signal based on reg_count and bit_count
always@(posedge clk or negedge reset_n) begin 
    if(!reset_n) begin
        serial_out <= 1'b0;                                 // Reset serial output
    end
    else if(serial_out_enable) begin
        serial_out <= data_reg[0];                          // Output the least significant bit of data_reg
    end
end

// Set the done signal when transmission is complete (bit_count reaches zero)
// Using pre-computed condition for better timing
always@(posedge clk or negedge reset_n) begin
    if(!reset_n) begin
        done <= 1'b0;                                       // Reset done output
    end 
    else begin
        if(bit_count_is_zero) begin
            done <= 1'b1;                                   // Set done signal high when transmission is done
        end
        else begin 
            done <= 1'b0;                                   // Clear done signal during transmission
        end
    end
end

endmodule

///// rx_block
module rx_block(
    input wire clk,                 // clock input
    input wire reset_n,             // Active-low reset
    input wire data_in,             // Serial input data	
    input wire serial_clk,          // Clock signal for serial data
    input wire [2:0] sel,           // Selection output to choose data width
    output reg done,                // Done signal to indicate data reception complete		
    output reg [63:0] data_out      // Parallel output data after serial operation
);

    // Internal registers
    reg [63:0] data_reg;            // Register to hold incoming serial data
    reg [7:0] bit_count;            // Counter for the number of bits received	
    reg [7:0] count;                // General purpose counter to sync with bit_count

    // One-hot pre-decode for sel signal (L5 optimization)
    wire sel_is_000 = (sel == 3'b000);
    wire sel_is_001 = (sel == 3'b001);
    wire sel_is_010 = (sel == 3'b010);
    wire sel_is_011 = (sel == 3'b011);
    wire sel_is_100 = (sel == 3'b100);

    // Condition pre-computation for done signal (L6 optimization: wire decomposition)
    // Decompose the done condition into two parallel comparisons for better timing
    wire count_geq_bitcount = (count >= bit_count);
    wire count_nonzero = (count != 8'd0);
    wire done_condition = count_geq_bitcount & count_nonzero;

    // L5 optimization: Pre-compute count increment condition
    wire bit_count_gt_0 = (bit_count > 8'd0);
    wire count_inc_cond = !done_condition & bit_count_gt_0;

    // L5 optimization: Pre-compute data_out data slice outside always block (late mux-select)
    // Critical path improvement: the sel→data_reg mux tree evaluates in PARALLEL with
    // the done_condition computation. Only a simple 2:1 mux at data_out register input
    // depends on both paths.
    // Before: count,bit_count → done_condition (6 gates) → 5:1 sel mux (4 gates) → reg (10 levels)
    // After:  count,bit_count → done_condition (6 gates) ∥ sel → data slice (4 gates)
    //         → 2:1 done_condition mux (2 gates) → reg (8 levels, -2 gate savings)
    wire [63:0] data_reg_slice = (sel_is_000) ? 64'h0 :
                                 (sel_is_001) ? {56'h0, data_reg[7:0]} :
                                 (sel_is_010) ? {48'h0, data_reg[15:0]} :
                                 (sel_is_011) ? {32'h0, data_reg[31:0]} :
                                 (sel_is_100) ? data_reg :
                                 64'h0;

    // Sequential logic block to capture serial data on the rising edge of serial_clk
    always @(posedge serial_clk or negedge reset_n) begin
        if (!reset_n) begin         // Reset all registers on reset_n (active low)
            data_reg <= 64'h0;      // Clear the data register
            bit_count <= 8'd0;      // Clear the bit counter
        end else begin
            if(done == 1'b1) begin  // If done signal is asserted, reset the bit counter and data register  
                bit_count <= 8'b0;
                data_reg <= 64'h0;
            end
            else begin
                bit_count <= bit_count + 1'b1;              // Increment bit count
                data_reg[bit_count] <= data_in;             // Store the incoming data bit 
            end
        end
    end  
    
    // Sequential logic block to monitor the completion of data reception and update outputs
    // L5 optimization: data_out uses pre-computed data_reg_slice — only a 2:1 mux remains
    // inside the always block. The sel mux tree depth is removed from this critical path.
    always@(posedge clk or negedge reset_n) begin
        if(!reset_n) begin                                  // Reset all registers on reset_n (active low)
            count <= 8'd0;                                  // Clear the bit counter
            done <= 1'b0;                                   // Deassert done signal
            data_out <= 64'h0;                              // Clear the output data register					 
        end 
        else if(done_condition) begin                       // When the count reaches the bit_count, assert done and output the data
            done <= 1'b1;                                   // Set done to indicate transmission complete
            data_out <= data_reg_slice;                     // L5: Pre-computed slice selected by simple done_condition mux
        end
        else if(count_inc_cond) begin                       // L5 optimization: Use precomputed condition
            count <= count + 1'b1;                          // Increment count
            done <= 1'b0;                                   // Clear done signal while receiving
        end
        else begin                                          // If no bits have been received, reset the count and deassert done
            count <= 8'd0;                                  // Reset count
            done <= 1'b0;                                   // Clear done signal   
        end 
    end

endmodule