"""Use OpenRAM's own Verilog writer before slow SPICE characterization finishes.
Preview only: generated files MUST match full compiler outputs before admission.
No Liberty models or physical metrics are generated here.
"""
import sys, math
from pathlib import Path
sys.path.insert(0, '/openram')
from common import make_openram_package
make_openram_package()
import openram
openram.init_openram(sys.argv[1])
from openram.base.verilog import verilog
from openram import OPTS
v=verilog()
v.name=OPTS.output_name
v.word_size=OPTS.word_size
v.num_words=OPTS.num_words
v.num_banks=1
v.bank_addr_size=int(math.log2(v.num_words))
v.write_size=OPTS.write_size
v.num_spare_cols=0
v.readwrite_ports=list(range(OPTS.num_rw_ports))
v.write_ports=list(range(OPTS.num_rw_ports+OPTS.num_w_ports))
v.read_ports=v.readwrite_ports+list(range(OPTS.num_rw_ports+OPTS.num_w_ports,OPTS.num_rw_ports+OPTS.num_w_ports+OPTS.num_r_ports))
v.all_ports=sorted(set(v.write_ports+v.read_ports))
p=Path('/out/model-preview');p.mkdir(exist_ok=True)
v.verilog_write(str(p/(v.name+'.v')))
print(v.name, 'preview generated by upstream OpenRAM writer')
