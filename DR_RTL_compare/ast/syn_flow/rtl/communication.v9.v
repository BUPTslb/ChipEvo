`timescale 1ns / 1ps
module sync_serial_communication_tx_rx(
    input clk,                     // Clock signal
    input reset_n,                 // Active low reset signal
    input [2:0] sel,               // Selection signal for TX block
    input [63:0] data_in,          // 64-bit data input for TX block
    output [63:0] data_out,        // 64-bit data output from RX block
    output done                    // Done signal indicating completion
);

// Internal signals
wire tx_out;                       // Serial data output from TX block
wire tx_done;                      // Done signal from TX block
wire serial_clk_in;                // Serial clock generated by TX block

// Instantiate the TX block
tx_block uut_tx_block (
    .clk(clk),                     // Clock input to TX block
    .reset_n(reset_n),             // Reset input to TX block
    .data_in(data_in),             // 64-bit data input to TX block
    .sel(sel),                     // Selection signal to TX block
    .serial_out(tx_out),           // Serial data output from TX block
    .done(tx_done),                // Done signal from TX block
    .serial_clk(serial_clk_in)     // Serial clock output from TX block
);

// Instantiate the RX block
rx_block uut_rx_block (
    .clk(clk),                     // Clock input to RX block
    .serial_clk(serial_clk_in),    // Serial clock input to RX block
    .reset_n(reset_n),             // Reset input to RX block
    .sel(sel),                     // Selection signal to RX block
    .data_in(tx_out),              // Serial data input to RX block
    .data_out(data_out),           // 64-bit data output from RX block
    .done(done)                    // Done signal from RX block
);

endmodule

///// tx_block
module tx_block(
    input clk,               // Clock input
    input reset_n,           // Active-low reset input
    input [63:0] data_in,    // 64-bit parallel data input
    input [2:0] sel,         // Selection input to choose data width
    output reg serial_out,   // Serial data output
    output reg done,         // Done signal indicating completion of transmission
    output serial_clk        // Clock for serial data transmission
);

// Internal registers
reg [63:0] data_reg;         // Register to hold the data being transmitted
reg [6:0] bit_count;         // Counter to track number of bits to transmit
reg [6:0] reg_count;         // Register for counting bits for serial clock control
reg [6:0] temp_reg_count;    // Temporary register to track reg_count

// One-hot pre-decode for sel signal (L5 optimization)
wire sel_is_000 = (sel == 3'b000);
wire sel_is_001 = (sel == 3'b001);
wire sel_is_010 = (sel == 3'b010);
wire sel_is_011 = (sel == 3'b011);
wire sel_is_100 = (sel == 3'b100);

// Condition pre-computation for done signal (L5 optimization)
wire bit_count_is_zero = (bit_count == 7'h0);
wire bit_count_positive = (bit_count > 7'h0);

// L5 optimization: Pre-decode sel AND done combinations.
// These named wires make the load-mux select logic single-level,
// reducing combinational depth from sel/done to data_reg/bit_count.
wire sel000_and_done = sel_is_000 & done;
wire sel001_and_done = sel_is_001 & done;
wire sel010_and_done = sel_is_010 & done;
wire sel011_and_done = sel_is_011 & done;
wire sel100_and_done = sel_is_100 & done;

// L5 optimization: Pre-decode combined load signals.
// sel000 loads zero, so sel000_and_done is a no-op load (data=0, count=0).
// When done & none-of-the-above, also load zero (default case).
wire sel_narrow_and_done = sel001_and_done | sel010_and_done | sel011_and_done | sel100_and_done;

// L5 optimization: Balanced ternary mux tree for bit_count load values
// Restructure nested if-else into parallel selection with balanced 2:1 mux tree
wire [6:0] bit_count_load_sel001 = sel001_and_done ? 7'd7 : 7'h0;
wire [6:0] bit_count_load_sel010 = sel010_and_done ? 7'd15 : 7'h0;
wire [6:0] bit_count_load_sel011 = sel011_and_done ? 7'd31 : 7'h0;
wire [6:0] bit_count_load_sel100 = sel100_and_done ? 7'd63 : 7'h0;

// Level 1: OR combine parallel outputs (balanced tree)
wire [6:0] bit_count_load_l1_01 = bit_count_load_sel001 | bit_count_load_sel010;
wire [6:0] bit_count_load_l1_23 = bit_count_load_sel011 | bit_count_load_sel100;
// Level 2: Final OR
wire [6:0] bit_count_load_value = bit_count_load_l1_01 | bit_count_load_l1_23;

// L5 optimization: Balanced ternary mux tree for data_reg load values
// Compute all branch values in parallel for balanced tree
wire [63:0] data_load_sel001 = sel001_and_done ? {56'h0, data_in[7:0]} : 64'h0;
wire [63:0] data_load_sel010 = sel010_and_done ? {48'h0, data_in[15:0]} : 64'h0;
wire [63:0] data_load_sel011 = sel011_and_done ? {32'h0, data_in[31:0]} : 64'h0;
wire [63:0] data_load_sel100 = sel100_and_done ? data_in[63:0] : 64'h0;

// Level 1: OR combine parallel outputs (balanced tree)
wire [63:0] data_load_l1_01 = data_load_sel001 | data_load_sel010;
wire [63:0] data_load_l1_23 = data_load_sel011 | data_load_sel100;
// Level 2: Final OR
wire [63:0] data_load_value = data_load_l1_01 | data_load_l1_23;

// Sequential block for state control and data selection
// L5 optimization: Late mux-select on bit_count and data_reg.
// Load-path values computed in parallel using balanced mux tree,
// then selected with single 2:1 mux on 'done'.
always @(posedge clk or negedge reset_n) begin
    if (!reset_n) begin
        // Reset all values on active-low reset
        data_reg     <= 64'h0;
        bit_count    <= 7'h0;
        reg_count    <= 7'h0;
    end else begin
        // --- bit_count: late mux-select with balanced tree ---
        // Mux structure: done ? load : (bit_count_positive ? dec : hold)
        if (done) begin
            bit_count <= bit_count_load_value;
        end else if (bit_count_positive) begin
            bit_count  <= bit_count - 1'b1;
        end

        // --- data_reg: late mux-select with balanced tree ---
        // Load value computed with balanced mux tree, then final 2:1 mux
        if (done) begin
            data_reg <= data_load_value;
        end else if (bit_count_positive) begin
            data_reg   <= data_reg >> 1;
        end

        reg_count <= bit_count;
    end
end

// L6 optimization: Extract condition for serial_clk into named wire
wire temp_reg_count_nonzero = (temp_reg_count != 7'd0);
// Generate serial clock based on temp_reg_count
assign serial_clk = clk && temp_reg_count_nonzero;

// Register to keep track of reg_count and use for clock gating
always@(posedge clk or negedge reset_n) begin 
    if(!reset_n) begin
        temp_reg_count <= 7'h0;
    end
    else begin
        temp_reg_count <= reg_count;
    end
end

// Sequential logic to drive the serial_out signal based on reg_count and bit_count
wire serial_out_enable = (reg_count > 7'h0) || bit_count_positive;

always@(posedge clk or negedge reset_n) begin 
    if(!reset_n) begin
        serial_out <= 1'b0;
    end
    else if(serial_out_enable) begin
        serial_out <= data_reg[0];
    end
end

// Set the done signal when transmission is complete (bit_count reaches zero)
always@(posedge clk or negedge reset_n) begin
    if(!reset_n) begin
        done <= 1'b0;
    end 
    else begin
        if(bit_count_is_zero) begin
            done <= 1'b1;
        end
        else begin 
            done <= 1'b0;
        end
    end
end

endmodule

///// rx_block
module rx_block(
    input wire clk,
    input wire reset_n,
    input wire data_in,
    input wire serial_clk,
    input wire [2:0] sel,
    output reg done,
    output reg [63:0] data_out
);

    // Internal registers
    reg [63:0] data_reg;
    reg [7:0] bit_count;
    reg [7:0] count;

    // One-hot pre-decode for sel signal (L5 optimization)
    wire sel_is_000 = (sel == 3'b000);
    wire sel_is_001 = (sel == 3'b001);
    wire sel_is_010 = (sel == 3'b010);
    wire sel_is_011 = (sel == 3'b011);
    wire sel_is_100 = (sel == 3'b100);

    // Condition pre-computation for done signal (L6 optimization)
    // count_geq_bitcount and count_nonzero decompose the done condition
    // for parallel evaluation by synthesis
    wire count_geq_bitcount = (count >= bit_count);
    wire count_nonzero = (count != 8'd0);
    wire done_condition = count_geq_bitcount & count_nonzero;

    // L6 optimization: count_eq_bitcount is the key equality comparison.
    // When count < bit_count (i.e., !count_eq_bitcount), bit_count is
    // guaranteed to be > 0 since count >= 0. Therefore the count increment
    // condition can be simplified: remove the redundant bit_count_gt_0 AND
    // term. This eliminates an AND gate from the count mux-select path,
    // reducing combinational depth on the count critical path.
    wire count_eq_bitcount = (count == bit_count);

    // Sequential logic block to capture serial data on the rising edge of serial_clk
    always @(posedge serial_clk or negedge reset_n) begin
        if (!reset_n) begin
            data_reg <= 64'h0;
            bit_count <= 8'd0;
        end else begin
            if(done == 1'b1) begin
                bit_count <= 8'b0;
                data_reg <= 64'h0;
            end
            else begin
                bit_count <= bit_count + 1'b1;
                data_reg[bit_count] <= data_in;
            end
        end
    end  
    
    // Done signal computation
    wire done_next = done_condition;
    
    // Sequential logic block for done signal
    always @(posedge clk or negedge reset_n) begin
        if (!reset_n)
            done <= 1'b0;
        else
            done <= done_next;
    end

    // Sequential logic block to monitor the completion of data reception and update count/data_out
    always@(posedge clk or negedge reset_n) begin
        if(!reset_n) begin
            count <= 8'd0;
            data_out <= 64'h0;
        end 
        else if(done_condition) begin
            // L5 optimization: Balanced ternary mux for data_out
            data_out <= (sel_is_000) ? 64'h0 :
                        (sel_is_001) ? {56'h0, data_reg[7:0]} :
                        (sel_is_010) ? {48'h0, data_reg[15:0]} :
                        (sel_is_011) ? {32'h0, data_reg[31:0]} :
                        (sel_is_100) ? data_reg :
                        64'h0;
        end
        // L6 optimization: Simplified count increment condition.
        // Removed redundant bit_count_gt_0 term — when count < bit_count
        // (!count_eq_bitcount), bit_count is guaranteed > 0 since count >= 0.
        // This removes one AND gate from the count mux-select critical path.
        else if(!count_eq_bitcount) begin
            count <= count + 1'b1;
        end
        else begin
            count <= 8'd0;
        end 
    end

endmodule